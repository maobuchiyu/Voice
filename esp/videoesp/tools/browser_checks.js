async (page) => {
  const check=(ok,message)=>{if(!ok)throw new Error(message);};
  const fixture=async query=>page.request.get('http://127.0.0.1:8080/__test?'+query);
  const text=id=>page.locator('#'+id).textContent();
  const ready=()=>page.waitForFunction(()=>document.querySelector('#notice').textContent.includes('查询成功'));
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await fixture('silent=0&fft=2048&generator=1&reboot=1');await page.reload();await ready();
  for(let i=0;i<6;i++) { await page.reload(); await ready(); }
  await page.waitForFunction(()=>document.querySelector('#rxBytes').textContent==='100,000 B');
  console.log('Ready; checking device controls');
  check(await page.locator('#startButton').isEnabled(),'Start must be enabled in IDLE');
  await page.locator('#startButton').click();
  await page.waitForFunction(()=>document.querySelector('#displayState').textContent==='实时更新');
  console.log('RTA data received');
  await page.locator('#pauseButton').click();const before=await text('frameLabel');
  await page.waitForTimeout(550);check((await text('frameLabel'))===before,'Pause changed the displayed frame');
  await page.locator('#singleButton').click();
  await page.waitForFunction(()=>document.querySelector('#notice').textContent.includes('单次预览已捕获'));
  check((await text('frameLabel'))!==before,'Single did not capture a new frame');
  console.log('Pause and single preview passed');
  await page.locator('#pauseButton').click();await page.locator('#autosetButton').click();
  await page.locator('#spectrumTab').click();
  check(await page.locator('#emptyState').isHidden(),'Spectrum fixture was not displayed');
  await page.locator('#toneFrequency').fill('4321');await page.locator('#toneLevel').fill('-20');await page.locator('#toneOnButton').click();
  await page.waitForFunction(()=>document.querySelector('#generatorState').textContent==='输出中');
  check((await text('generatorHint')).includes('4,321'),'Applied tone frequency is not confirmed');
  await page.locator('#toneOffButton').click();await page.waitForFunction(()=>document.querySelector('#generatorState').textContent==='已关闭');
  await page.locator('#input').selectOption('loop');await page.locator('#gainNote').fill('增益固定, "中间"');
  await page.locator('#saveButton').click();await page.waitForFunction(()=>document.querySelector('#notice').textContent.includes('设置已保存'));
  await page.reload();await ready();check(await page.locator('#input').inputValue()==='loop','Saved input did not restore');
  console.log('Tone and settings passed');
  check(await page.locator('#gainNote').inputValue()==='增益固定, "中间"','Saved note did not restore');
  await page.waitForFunction(()=>document.querySelector('#emptyState').hidden);
  const json=page.waitForEvent('download');await page.locator('#jsonButton').click();await (await json).saveAs('output/playwright/acousticlab-snapshot.json');
  const csv=page.waitForEvent('download');await page.locator('#csvButton').click();await (await csv).saveAs('output/playwright/acousticlab-snapshot.csv');
  await fixture('silent=1');await page.locator('#stopButton').click();
  await page.waitForFunction(()=>document.querySelector('#notice').textContent.includes('未收到 C5 回复'));
  check((await text('modePill'))==='RTA','Timeout falsely changed the device mode');
  check(await page.locator('#stopButton').isEnabled(),'Timeout left controls locked');await fixture('silent=0');
  console.log('Downloads and timeout passed');
  await fixture('bad=1');await page.waitForTimeout(150);
  check((await text('badFrames')).includes('页面 1'),'Malformed frame was not rejected');
  await fixture('disconnect=1');await page.waitForFunction(()=>document.querySelector('#connectionLabel').textContent.includes('重连'));
  await ready();check((await text('modePill'))==='RTA','Reconnect changed the device mode');
  await fixture('reboot=1');await page.waitForFunction(()=>document.querySelector('#modePill').textContent==='IDLE');
  check(await page.locator('#jsonButton').isDisabled(),'Reboot kept stale export data');
  await page.locator('#startButton').click();await page.waitForFunction(()=>document.querySelector('#emptyState').hidden);
  await page.setViewportSize({width:1440,height:1000});await page.waitForTimeout(300);
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Desktop horizontal overflow');
  await page.screenshot({path:'output/playwright/acousticlab-desktop-spectrum.png',fullPage:true});
  await page.locator('#scopeTab').click();await page.screenshot({path:'output/playwright/acousticlab-desktop-scope.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(300);
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile horizontal overflow');
  await page.screenshot({path:'output/playwright/acousticlab-mobile-scope.png',fullPage:true});
  await page.locator('#spectrumTab').click();await page.screenshot({path:'output/playwright/acousticlab-mobile-spectrum.png',fullPage:true});
  await fixture('fft=0&generator=0');await page.waitForFunction(()=>document.querySelector('#emptyTitle').textContent.includes('尚未提供频谱'));
  check(await page.locator('#toneOnButton').isDisabled(),'Unsupported generator control is enabled');
  check((await text('frequency')).startsWith('—'),'Unsupported FFT displayed a fake frequency');
  await page.locator('#helpButton').click();check(await page.locator('#helpDialog').isVisible(),'Help did not open');await page.locator('#closeHelp').click();
  await page.locator('#stopButton').click();await page.waitForFunction(()=>document.querySelector('#modePill').textContent==='IDLE');
  check(errors.length===0,'Browser errors: '+errors.join('; '));
  return {result:'PASS',scenarios:['start/stop','pause','single','autoset','spectrum','tone command','settings reload','CSV/JSON','timeout mode preservation','malformed CRC','disconnect/reconnect','C5 reboot','desktop/mobile overflow','unsupported C5 capabilities','help'],browserErrors:errors};
}
